import { chromium } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
const dir = path.resolve('artifacts/pitch/.build/assets')
await fs.mkdir(dir,{recursive:true})
const browser = await chromium.launch({headless:true})
const context = await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2,locale:'en-IN'})
const page = await context.newPage()
await page.goto('http://localhost:4173/#/day')
await page.evaluate(()=>document.fonts.ready)
await page.locator('.daylist').screenshot({path:path.join(dir,'today.png')})
await page.goto('http://localhost:4173/#/patient/P-0417')
await page.locator('.pgrid').first().screenshot({path:path.join(dir,'kidney-map.png')})
await page.getByTestId('val-uacr-2025-09-18').click()
await page.locator('.viewer [data-hl="1"]').waitFor()
