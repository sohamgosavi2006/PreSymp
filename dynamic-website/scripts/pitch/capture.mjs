await page.locator('.viewer').screenshot({path:path.join(dir,'source-proof.png')})
await page.getByRole('button',{name:'Close source report',exact:true}).click()
await page.locator('.pgrid.low').screenshot({path:path.join(dir,'schedule-reports.png')})
await page.goto('http://localhost:4173/#/card/P-0417')
await page.getByRole('button',{name:'EN',exact:true}).click()
await page.getByRole('button',{name:'Doctor',exact:true}).click()
await page.getByLabel('Next appointment').fill('2026-01-15')
